/** Look up a country by slug. Returns undefined for invalid slugs. */
export function getCountry(slug: string): CountryData | undefined {
  return COUNTRIES.find((c) => c.slug === slug);
}

/** All valid country slugs — used for generateStaticParams */
export const COUNTRY_SLUGS = COUNTRIES.map((c) => c.slug);

/** Group countries by region */
export function getCountriesByRegion(): Record<Region, CountryData[]> {
  return COUNTRIES.reduce(
    (acc, c) => {
      acc[c.region] = [...(acc[c.region] ?? []), c];
      return acc;
    },
    {} as Record<Region, CountryData[]>
  );
}
